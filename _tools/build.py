"""Static build helpers for the demo.

1. Writes shared/photos.js (photo data for the gallery pages) from shared/photos.json.
2. Expands every <img data-photo="slug"> in the HTML pages into a responsive,
   blur-up <img> (src, srcset, width, height, alt, LQIP background). Idempotent:
   re-run it after editing any page.

3. With SITE_URL set, rewrites og:image / og:url to absolute URLs (WhatsApp and most
   social apps ignore relative ones). The relative source is kept in data-rel, so the
   step can be re-run against a different host.

Usage: python3 _tools/build.py
       SITE_URL=https://example.github.io/ashley-demo/ python3 _tools/build.py
"""
import json, os, re, glob
from urllib.parse import urljoin

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
photos = json.load(open(os.path.join(ROOT, 'shared', 'photos.json')))
by_slug = {p['slug']: p for p in photos}

COLLECTIONS = [
    dict(id='noir', name='Noir', cover='funmilola',
         quote='Colour is everything, black and white is more.', by='Dominic Rouse'),
    dict(id='vivid', name='Vivid', cover='kasia-hat',
         quote='Colours, like features, follow the changes of the emotions.', by='Pablo Picasso'),
    dict(id='sensual', name='Sensual', cover='jess-shawl',
         quote='I love humanity, I adore it, it’s sensational, sensuous, exciting.', by='David Bowie'),
    dict(id='urban', name='Urban', cover='jess-collar',
         quote='In a portrait, I’m looking for the silence in somebody.', by='Henri Cartier-Bresson'),
    dict(id='streets', name='Streets', cover='tate-phone',
         quote='I often look for the temporary in a street scene, capturing what is here now and won’t be there tomorrow.', by='Ashley Meerloo'),
    dict(id='arts', name='Arts', cover='final-ballad',
         quote='I regard the theatre as the greatest of all art forms, the most immediate way in which a human being can share with another the sense of what it is to be a human being.', by='Oscar Wilde'),
]

slim = [dict(slug=p['slug'], c=p['c'], alt=p['alt'], w=p['w'], h=p['h'], s=p['s'], lqip=p['lqip'], bg=p['bg'])
        for p in photos if p['c'] != 'site']
with open(os.path.join(ROOT, 'shared', 'photos.js'), 'w') as f:
    f.write('/* Generated by _tools/build.py — do not edit by hand. */\n')
    f.write('window.COLLECTIONS = ' + json.dumps(COLLECTIONS, ensure_ascii=False) + ';\n')
    f.write('window.PHOTOS = ' + json.dumps(slim, ensure_ascii=False, separators=(',', ':')) + ';\n')

IMG = re.compile(r'<img\b[^>]*\bdata-photo="([^"]+)"[^>]*>', re.S)
MANAGED = re.compile(r'\s(?:src|srcset|data-src|data-srcset|width|height|style|decoding)="[^"]*"', re.S)

def expand(match, prefix):
    """data-defer images get data-src/data-srcset; the page JS promotes them after load."""
    tag, slug = match.group(0), match.group(1)
    p = by_slug[slug]
    srcset = ', '.join(f'{prefix}shared/img/{slug}-{label}.webp {actual}w' for label, actual in p['s'])
    mid = next((l for l, a in p['s'] if l == 960), p['s'][-1][0])
    old = re.search(r'\sstyle="([^"]*)"', tag)
    keep = re.sub(r'background:#[0-9a-f]{6} url\([^)]*\) center/cover no-repeat;?', '', old.group(1)).strip(' ;') if old else ''
    tag = MANAGED.sub('', tag)
    lazy = 'data-' if 'data-defer' in tag else ''
    style = (keep + ';' if keep else '') + f'background:{p["bg"]} url({p["lqip"]}) center/cover no-repeat'
    attrs = (f' {lazy}src="{prefix}shared/img/{slug}-{mid}.webp" {lazy}srcset="{srcset}" width="{p["w"]}" height="{p["h"]}"'
             f' decoding="async" style="{style}"')
    if not re.search(r'\salt="', tag):
        attrs += f' alt="{p["alt"]}"'
    return tag[:4] + attrs + tag[4:]

SITE_URL = os.environ.get('SITE_URL', '').strip()
if SITE_URL and not SITE_URL.endswith('/'):
    SITE_URL += '/'
META = re.compile(r'<meta property="(og:image|og:url)" content="([^"]*)"(?: data-rel="([^"]*)")?>')

def absolutise(html, rel_path):
    page_url = urljoin(SITE_URL, rel_path.replace(os.sep, '/'))
    def fix(m):
        prop, content, rel = m.group(1), m.group(2), m.group(3) or m.group(2)
        return f'<meta property="{prop}" content="{urljoin(page_url, rel)}" data-rel="{rel}">'
    return META.sub(fix, html)

for path in glob.glob(os.path.join(ROOT, '**', '*.html'), recursive=True):
    if '/_tools/' in path:
        continue
    rel_path = os.path.relpath(path, ROOT)
    depth = rel_path.count(os.sep)
    prefix = '../' * depth
    html = open(path).read()
    out = IMG.sub(lambda m: expand(m, prefix), html)
    if SITE_URL:
        out = absolutise(out, rel_path)
    if out != html:
        open(path, 'w').write(out)
        print('expanded', os.path.relpath(path, ROOT), len(IMG.findall(out)), 'images')
print('photos.js written:', len(slim), 'photos')
